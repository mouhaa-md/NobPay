#!/usr/bin/env node
/**
 * Builds src/components/ui/icons.generated.ts: only the Material Symbols this app uses, as SVG path data
 * (outlined, weight 400, Apache-2.0). It replaces the 1.1 MB icon font that every page used to download.
 *
 * Usage:  node scripts/build-icons.mjs [folder of the unpacked @material-symbols/svg-400 package]
 * Without an argument the package is fetched with `npm pack` into a temporary folder (network needed).
 * An "icon in use" is any quoted snake_case string under src/ that is also the name of a Material Symbol.
 * Run it again after adding an icon; tests/icons.test.ts fails when a used icon is missing.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '0.48.2';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'src');
const outFile = path.join(srcDir, 'components', 'ui', 'icons.generated.ts');

function unpackedPackage() {
  const given = process.argv[2];
  if (given) return path.resolve(given);
  const tmp = mkdtempSync(path.join(tmpdir(), 'nobpay-icons-'));
  const shell = process.platform === 'win32';
  execFileSync('npm', ['pack', `@material-symbols/svg-400@${VERSION}`, '--silent'], { cwd: tmp, shell, stdio: 'inherit' });
  execFileSync('tar', ['-xzf', `material-symbols-svg-400-${VERSION}.tgz`], { cwd: tmp, stdio: 'inherit' });
  return path.join(tmp, 'package');
}

function* sourceFiles(dir) {
  for (const name of readdirSync(dir)) {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) yield* sourceFiles(p);
    else if (/\.(ts|tsx)$/.test(name) && !name.endsWith('icons.generated.ts')) yield p;
  }
}

const pkg = unpackedPackage();
const folder = path.join(pkg, 'outlined');
if (!existsSync(folder)) throw new Error(`Dossier introuvable : ${folder}`);
const available = new Set(readdirSync(folder).filter((f) => f.endsWith('.svg') && !f.endsWith('-fill.svg')).map((f) => f.slice(0, -4)));

const candidates = new Set();
for (const file of sourceFiles(srcDir)) {
  for (const m of readFileSync(file, 'utf8').matchAll(/(['"`])([a-z][a-z0-9_]{1,40})\1/g)) candidates.add(m[2]);
}
const used = [...candidates].filter((n) => available.has(n)).sort();

const pathOf = (file) => {
  const svg = readFileSync(file, 'utf8');
  const d = /<path d="([^"]+)"/.exec(svg);
  if (!d || !svg.includes('viewBox="0 -960 960 960"')) throw new Error(`SVG inattendu : ${file}`);
  return d[1];
};

const lines = used.map((name) => {
  const outlined = pathOf(path.join(folder, `${name}.svg`));
  const fillFile = path.join(folder, `${name}-fill.svg`);
  const filled = existsSync(fillFile) ? pathOf(fillFile) : undefined;
  return `  ${name}: [${JSON.stringify(outlined)}${filled ? `, ${JSON.stringify(filled)}` : ''}],`;
});

writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/build-icons.mjs, do not edit by hand.
// Material Symbols (outlined, weight 400), Apache-2.0, \`@material-symbols/svg-400@${VERSION}\`. viewBox "0 -960 960 960".
export const ICONS: Record<string, readonly [outlined: string, filled?: string]> = {
${lines.join('\n')}
};
`,
);
console.log(`${used.length} icônes écrites dans ${path.relative(root, outFile)} (${(statSync(outFile).size / 1024).toFixed(1)} Ko)`);
